"""
Pydantic schemas for the pitch-deck analyzer endpoint.
"""

from __future__ import annotations

from typing import Any, Literal

from pydantic import BaseModel, Field


class PitchDeckRequest(BaseModel):
    text: str = Field(
        ...,
        min_length=1,
        max_length=100_000,
        description="Full pitch-deck text. Plain text only.",
    )


class PitchDeckResponse(BaseModel):
    status: Literal["success"] = "success"
    overall_completeness_score: float = Field(..., ge=0.0, le=100.0)
    sections: dict[str, Any]
    information_gaps: list[dict[str, Any]]
    summary: dict[str, Any]
    disclaimer: str = (
        "Analysis generated by a model trained on synthetic development data. "
        "Not investment advice."
    )